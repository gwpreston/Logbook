<?php

declare(strict_types=1);

/*
 * Write THIRD-PARTY-NOTICES.md: the licence of everything Logbook ships that
 * it didn't write (spec.md §1, docs/phases/phase-45.md).
 *
 *   php bin/third-party-notices.php            # (re)writes THIRD-PARTY-NOTICES.md
 *   php bin/third-party-notices.php --check    # CI: fails when stale or a licence isn't allowed
 *   php bin/third-party-notices.php [--check] <composer.lock> <vendor notices> <output>
 *
 * Sources: the production packages in composer.lock (dev tools aren't
 * shipped), and assets/vendor/THIRD-PARTY-NOTICES.txt, which
 * `npm run vendor` writes for the bundled JS, fonts and icons. Every licence
 * must be on ALLOWED, the licences that can be combined with Logbook's
 * AGPL-3.0-or-later; a package offering several (Composer's "or") passes
 * when one of them is allowed. A new licence means checking it fits first,
 * then adding it here.
 */

const ALLOWED = [
    '0BSD', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'CC0-1.0', 'ISC', 'MIT', 'MPL-2.0', 'OFL-1.1',
    'Unlicense', 'Zlib',
    'LGPL-2.1', 'LGPL-2.1-only', 'LGPL-2.1-or-later', 'LGPL-3.0', 'LGPL-3.0-only', 'LGPL-3.0-or-later',
    'GPL-3.0-only', 'GPL-3.0-or-later', 'AGPL-3.0-only', 'AGPL-3.0-or-later',
];

$root = dirname(__DIR__);
$args = array_values(array_filter((array) ($_SERVER['argv'] ?? []), 'is_string'));
$check = in_array('--check', $args, true);
$paths = array_values(array_filter(array_slice($args, 1), static fn (string $a): bool => $a !== '--check'));
$lockFile = $paths[0] ?? $root . '/composer.lock';
$vendorFile = $paths[1] ?? $root . '/assets/vendor/THIRD-PARTY-NOTICES.txt';
$outFile = $paths[2] ?? $root . '/THIRD-PARTY-NOTICES.md';

$lock = json_decode((string) @file_get_contents($lockFile), true);
if (!is_array($lock) || !is_array($lock['packages'] ?? null)) {
    fwrite(STDERR, "Cannot read the packages in {$lockFile}\n");
    exit(2);
}
$vendorText = @file_get_contents($vendorFile);
if ($vendorText === false) {
    fwrite(STDERR, "Cannot read {$vendorFile}\n");
    exit(2);
}

$problems = [];

$allowed = static function (array $licenses): bool {
    foreach ($licenses as $license) {
        if (in_array($license, ALLOWED, true)) {
            return true;
        }
    }

    return false;
};
$cell = static fn (string $s): string => str_replace('|', '\|', $s);
$text = static fn (mixed $v): string => is_scalar($v) ? (string) $v : '';

$php = [];
foreach ($lock['packages'] as $package) {
    $package = is_array($package) ? $package : [];
    $name = $text($package['name'] ?? null);
    $licenses = array_values(array_diff(array_map($text, (array) ($package['license'] ?? [])), ['']));
    if (!$allowed($licenses)) {
        $problems[] = sprintf('%s: %s', $name, $licenses === [] ? 'no licence stated' : implode(' or ', $licenses));
    }
    $vcs = is_array($package['source'] ?? null) ? $package['source'] : [];
    $source = $text($package['homepage'] ?? $vcs['url'] ?? null);
    $php[$name] = sprintf(
        '| %s | %s | %s | %s |',
        $cell($name),
        $cell($text($package['version'] ?? null)),
        $cell($licenses === [] ? '—' : implode(' or ', $licenses)),
        $cell(preg_replace('/\.git$/', '', $source) ?? $source),
    );
}
ksort($php);

// "<file>: <package> <version> — <licence> license — <url>", one per line.
$assets = [];
foreach (preg_split('/\R/', $vendorText) ?: [] as $line) {
    if (preg_match('/^(.+?): (\S+) (\S+)(?: \((.+)\))? — (\S+) license — (\S+)$/u', trim($line), $m) !== 1) {
        continue;
    }
    if (!$allowed([$m[5]])) {
        $problems[] = sprintf('%s: %s', $m[2], $m[5]);
    }
    $what = $m[4] !== '' ? sprintf('%s (%s)', $m[2], $m[4]) : $m[2];
    $assets[] = sprintf('| `%s` | %s | %s | %s | %s |', $m[1], $cell($what), $m[3], $m[5], $m[6]);
}
if ($assets === []) {
    $problems[] = "{$vendorFile}: no bundled assets listed";
}

$notices = implode("\n", [
    '# Third-party notices',
    '',
    'Logbook is licensed under the GNU Affero General Public License v3.0 or',
    'later ([`LICENSE`](LICENSE)). It ships the third-party code and assets',
    'below, each under its own licence. Their copyright notices and licence',
    'texts are in the packages themselves: `vendor/<package>/` for PHP, and the',
    'upstream projects linked below for the bundled front-end files.',
    '',
    'Generated by `php bin/third-party-notices.php` from `composer.lock` and',
    '`assets/vendor/THIRD-PARTY-NOTICES.txt`; do not edit by hand. CI fails',
    'when this file is stale or a shipped dependency\'s licence is not on the',
    'script\'s allowlist.',
    '',
    '## PHP packages',
    '',
    'Production dependencies only; development tools are not shipped.',
    '',
    '| Package | Version | Licence | Source |',
    '|---|---|---|---|',
    ...array_values($php),
    '',
    '`smalot/pdfparser` (LGPL-3.0) is used unmodified, installed by Composer',
    'as a separate library; you may replace it with a compatible version.',
    '',
    '## Bundled front-end files',
    '',
    'In `assets/vendor/`, copied to `public/assets/vendor/`.',
    '',
    '| File | Package | Version | Licence | Source |',
    '|---|---|---|---|---|',
    ...$assets,
    '',
    'The icons are Material Symbols by Google, licensed under the Apache',
    'License, Version 2.0 (https://www.apache.org/licenses/LICENSE-2.0),',
    'bundled into one SVG sprite with only the icons Logbook uses. The fonts',
    'are licensed under the SIL Open Font License 1.1',
    '(https://openfontlicense.org) and are not sold on their own.',
    '',
    '## Data',
    '',
    'Fuel prices from UK Fuel Finder and MOT history from DVSA are fetched at',
    'run time, never shipped, and are used under the Open Government Licence',
    'v3.0 (https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/).',
    'Logbook shows their attribution wherever that data appears.',
    '',
]);

if ($problems !== []) {
    fwrite(STDERR, "Licences not on the allowlist in bin/third-party-notices.php:\n  " . implode("\n  ", $problems) . "\n");
    exit(1);
}

if ($check) {
    if (@file_get_contents($outFile) !== $notices) {
        fwrite(STDERR, "{$outFile} is stale. Run: php bin/third-party-notices.php\n");
        exit(1);
    }
    echo "Third-party notices are current; every licence is allowed.\n";
    exit(0);
}

if (file_put_contents($outFile, $notices) === false) {
    fwrite(STDERR, "Cannot write {$outFile}\n");
    exit(2);
}
echo "Wrote {$outFile}\n";
